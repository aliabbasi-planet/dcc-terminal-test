CREATE OR REPLACE VIEW DEV_CORE_AAB.DCC_REMEDIATION.V_CURRENT_BROKEN AS
WITH latest AS (
    -- Only the most recent load: a terminal repaired since an earlier snapshot has no
    -- row in the newest one and must drop out rather than resurface from an old date.
    SELECT * FROM DEV_CORE_AAB.DCC_REMEDIATION.HEALTH_DAILY_SNAPSHOT
    WHERE SNAPSHOT_DATE = (SELECT MAX(SNAPSHOT_DATE) FROM DEV_CORE_AAB.DCC_REMEDIATION.HEALTH_DAILY_SNAPSHOT)
),
fixed AS (
    -- Durable registry of verified PROD fixes (DCC_FIX_REGISTRY): a row
    -- is written when a live fix is verified by a fresh SQL-Server read (or a live
    -- pre-check proves the check already satisfied) and DELETED when a rollback is
    -- confirmed, so a later rollback re-opens the check. It survives the daily refresh,
    -- and UAT/DEV rehearsals never hide PROD work (only
    -- ENVIRONMENT = 'PROD' rows count). Only fixes newer than the source
    -- load the snapshot was built from count, so a terminal re-broken in a later load
    -- resurfaces (FIXED_AT_UTC and SOURCE_LAST_ALTERED are both UTC).
    SELECT l.TERMINAL_IDENTIFIER,
           ARRAY_AGG(DISTINCT g.CHECK_COLUMN) AS FIXED_CHECKS,
           MAX(g.FIXED_AT_UTC) AS LAST_FIX_AT_UTC
    FROM latest l
    JOIN DEV_CORE_AAB.DCC_REMEDIATION.DCC_FIX_REGISTRY g
      ON g.TERMINAL_IDENTIFIER = l.TERMINAL_IDENTIFIER
     AND g.ENVIRONMENT = 'PROD' AND g.STATUS = 'FIXED'
     AND g.FIXED_AT_UTC > l.SOURCE_LAST_ALTERED
    GROUP BY l.TERMINAL_IDENTIFIER
),
joined AS (
    SELECT l.*,
           COALESCE(f.FIXED_CHECKS, ARRAY_CONSTRUCT()) AS FIXED_CHECKS,
           f.LAST_FIX_AT_UTC
    FROM latest l
    LEFT JOIN fixed f ON f.TERMINAL_IDENTIFIER = l.TERMINAL_IDENTIFIER
),
scored AS (
    SELECT *,
        IFF(HANDLER_DCCENABLE_CHECK_O = 1 AND NOT ARRAY_CONTAINS('HANDLER_DCCENABLE_CHECK_O'::VARIANT, FIXED_CHECKS), 1, 0)
        + IFF(HANDLER_DCCENABLECOMPLETION_CHECK_O = 1 AND NOT ARRAY_CONTAINS('HANDLER_DCCENABLECOMPLETION_CHECK_O'::VARIANT, FIXED_CHECKS), 1, 0)
        + IFF(HANDLER_DCCENABLEAUTH_CHECK_O = 1 AND NOT ARRAY_CONTAINS('HANDLER_DCCENABLEAUTH_CHECK_O'::VARIANT, FIXED_CHECKS), 1, 0)
        + IFF(HANDLER_DCCENABLENFC_CHECK_O = 1 AND NOT ARRAY_CONTAINS('HANDLER_DCCENABLENFC_CHECK_O'::VARIANT, FIXED_CHECKS), 1, 0)
        + IFF(HANDLER_DCCENABLENFCSINGLETAP_CHECK_O = 1 AND NOT ARRAY_CONTAINS('HANDLER_DCCENABLENFCSINGLETAP_CHECK_O'::VARIANT, FIXED_CHECKS), 1, 0)
        + IFF(DCCXPRESSCO_CHECK_O = 1 AND NOT ARRAY_CONTAINS('DCCXPRESSCO_CHECK_O'::VARIANT, FIXED_CHECKS), 1, 0)
        + IFF(DCCXPRESSCODT_CHECK_O = 1 AND NOT ARRAY_CONTAINS('DCCXPRESSCODT_CHECK_O'::VARIANT, FIXED_CHECKS), 1, 0)
        + IFF(DCCXPRESSCOFALLBACK_CHECK_O = 1 AND NOT ARRAY_CONTAINS('DCCXPRESSCOFALLBACK_CHECK_O'::VARIANT, FIXED_CHECKS), 1, 0)
        + IFF(PRINTOUTTYPETEMPLATEDCC_CHECK_C = 1 AND NOT ARRAY_CONTAINS('PRINTOUTTYPETEMPLATEDCC_CHECK_C'::VARIANT, FIXED_CHECKS), 1, 0)
        + IFF(CONFIGDOWNLOAD_VERSION_CHECK_C = 1 AND NOT ARRAY_CONTAINS('CONFIGDOWNLOAD_VERSION_CHECK_C'::VARIANT, FIXED_CHECKS), 1, 0) AS OPEN_FIXABLE_CHECKS
    FROM joined
)
-- AWAITING_REFRESH: something was resolved and no fixable check is still open, so the
-- next load should clear it. Terminals whose only broken checks are not fixable here
-- stay ACTIONABLE (visible with "Fixable checks only" switched off).
SELECT *,
    CASE WHEN ARRAY_SIZE(FIXED_CHECKS) > 0 AND OPEN_FIXABLE_CHECKS = 0
         THEN 'AWAITING_REFRESH' ELSE 'ACTIONABLE' END AS REMEDIATION_STATE
FROM scored;

