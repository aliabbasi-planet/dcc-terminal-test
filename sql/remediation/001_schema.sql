CREATE OR REPLACE VIEW DEV_CORE_AAB.DCC_REMEDIATION.V_REMEDIATION_KPIS AS
SELECT
    (SELECT COUNT(*) FROM DEV_CORE_AAB.DCC_REMEDIATION.V_CURRENT_BROKEN
        WHERE REMEDIATION_STATE = 'ACTIONABLE')                       AS BROKEN_ACTIONABLE,
    (SELECT COUNT(*) FROM DEV_CORE_AAB.DCC_REMEDIATION.V_CURRENT_BROKEN
        WHERE REMEDIATION_STATE = 'AWAITING_REFRESH')                 AS AWAITING_REFRESH,
    -- One CORRELATION_ID per procedure call; one row per terminal it covered.
    (SELECT COUNT(DISTINCT CORRELATION_ID) FROM DEV_CORE_AAB.DCC_REMEDIATION.APP_FIX_LOG
        WHERE OUTCOME = 'APPLIED' AND MODE = 'LIVE' AND ENVIRONMENT = 'PROD')                              AS TOTAL_LIVE_FIXES,
    (SELECT COUNT(DISTINCT TERMINAL_IDENTIFIER) FROM DEV_CORE_AAB.DCC_REMEDIATION.APP_FIX_LOG
        WHERE OUTCOME = 'APPLIED' AND MODE = 'LIVE' AND ENVIRONMENT = 'PROD')                              AS UNIQUE_TERMINALS_FIXED,
    (SELECT COUNT(DISTINCT CORRELATION_ID) FROM DEV_CORE_AAB.DCC_REMEDIATION.APP_FIX_LOG
        WHERE OUTCOME = 'APPLIED' AND MODE = 'LIVE' AND NOT ENVIRONMENT = 'PROD')                          AS REHEARSAL_FIXES,
    (SELECT COUNT(*) FROM DEV_CORE_AAB.DCC_REMEDIATION.DCC_FIX_REGISTRY
        WHERE ENVIRONMENT = 'PROD' AND STATUS = 'FIXED') AS REGISTERED_FIXES,
    (SELECT MAX(SNAPSHOT_DATE) FROM DEV_CORE_AAB.DCC_REMEDIATION.HEALTH_DAILY_SNAPSHOT)            AS LATEST_SNAPSHOT_DATE;
