        FROM PROD_PRESENTATION.CORTEX.CORTEX_TERMINAL_MAINTENANCE
        WHERE TERMINAL_IDENTIFIER IN (
            SELECT TERMINAL_IDENTIFIER FROM DEV_CORE_AAB.DCC_REMEDIATION.DCC_FIX_REGISTRY
            WHERE ENVIRONMENT = 'PROD' AND STATUS = 'FIXED'
        )
        GROUP BY TERMINAL_IDENTIFIER
    )
    SELECT r.ENVIRONMENT,
               r.TERMINAL_IDENTIFIER,
               r.CHECK_COLUMN,
               r.FLAG_NAME,
               r.FIX_BIT,
               r.VALUE_SENT,
               r.TARGET_ID_KIND,
               r.TARGET_IDENTIFIER,
               r.INSTANCE_IDENTIFIER,
               r.LOCATION_NO,
