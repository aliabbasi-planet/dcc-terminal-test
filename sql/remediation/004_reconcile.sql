BEGIN
    BEGIN TRANSACTION;
    MERGE INTO DEV_CORE_AAB.DCC_REMEDIATION.DCC_CONFIRMED_FIXES tgt
USING (
    WITH cortex AS (
        SELECT TERMINAL_IDENTIFIER,
           MAX(COUNTRY_NAME) AS COUNTRY_NAME,
           MAX(REGION) AS REGION,
           MAX(INDUSTRY_NAME) AS INDUSTRY_NAME,
           MAX(BANK_MERCHANT_ID) AS BANK_MERCHANT_ID,
           MAX(MERCHANT_NAME) AS MERCHANT_NAME,
           MAX(CUSTOMER_NAME) AS CUSTOMER_NAME,
           MAX(ACQUIRER_NAME) AS ACQUIRER_NAME,
           MAX(LOCATION_NAME) AS LOCATION_NAME,
           MAX(TERMINAL_BRAND_NAME) AS TERMINAL_BRAND_NAME,
           MAX(TERMINAL_MODEL_NAME) AS TERMINAL_MODEL_NAME,
           MAX(FIRMWARE_VERSION) AS FIRMWARE_VERSION,
           MAX(IFF(LOCATION_DCCENABLED_BASE = 1 AND COALESCE(LOCATION_DCCENABLED_CHECK_C, 1) = 1, 1, 0)) AS LOCATION_DCCENABLED_CHECK_C,
           MAX(IFF(HANDLER_DCCENABLE_BASE = 1 AND COALESCE(HANDLER_DCCENABLE_CHECK_O, 1) = 1, 1, 0)) AS HANDLER_DCCENABLE_CHECK_O,
