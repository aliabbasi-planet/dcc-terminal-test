           MAX(IFF(DCCXPRESSCO_BASE = 1 AND COALESCE(DCCXPRESSCO_CHECK_O, 1) = 1, 1, 0)) AS DCCXPRESSCO_CHECK_O,
           MAX(IFF(DCCXPRESSCODT_BASE = 1 AND COALESCE(DCCXPRESSCODT_CHECK_O, 1) = 1, 1, 0)) AS DCCXPRESSCODT_CHECK_O,
           MAX(IFF(DCCXPRESSCOFALLBACK_BASE = 1 AND COALESCE(DCCXPRESSCOFALLBACK_CHECK_O, 1) = 1, 1, 0)) AS DCCXPRESSCOFALLBACK_CHECK_O,
           MAX(IFF(DCCMERCHANT_NO_BASE = 1 AND COALESCE(DCCMERCHANT_NO_CHECK_O, 1) = 1, 1, 0)) AS DCCMERCHANT_NO_CHECK_O,
