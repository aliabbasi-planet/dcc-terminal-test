           MAX(IFF(CONFIGDOWNLOAD_VERSION_CHECK_BASE = 1 AND COALESCE(CONFIGDOWNLOAD_VERSION_CHECK_C, 1) = 1, 1, 0)) AS CONFIGDOWNLOAD_VERSION_CHECK_C,
