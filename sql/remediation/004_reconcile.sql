      AND (CASE r.CHECK_COLUMN
                WHEN 'LOCATION_DCCENABLED_CHECK_C' THEN c.LOCATION_DCCENABLED_CHECK_C
                WHEN 'HANDLER_DCCENABLE_CHECK_O' THEN c.HANDLER_DCCENABLE_CHECK_O
                WHEN 'HANDLER_DCCENABLECOMPLETION_CHECK_O' THEN c.HANDLER_DCCENABLECOMPLETION_CHECK_O
                WHEN 'HANDLER_DCCENABLEAUTH_CHECK_O' THEN c.HANDLER_DCCENABLEAUTH_CHECK_O
                WHEN 'HANDLER_DCCENABLENFC_CHECK_O' THEN c.HANDLER_DCCENABLENFC_CHECK_O
                WHEN 'HANDLER_DCCENABLENFCSINGLETAP_CHECK_O' THEN c.HANDLER_DCCENABLENFCSINGLETAP_CHECK_O
                WHEN 'DCCFLAGSENABLED_CHECK_C' THEN c.DCCFLAGSENABLED_CHECK_C
                WHEN 'DCCXPRESSCO_CHECK_O' THEN c.DCCXPRESSCO_CHECK_O
                WHEN 'DCCXPRESSCODT_CHECK_O' THEN c.DCCXPRESSCODT_CHECK_O
                WHEN 'DCCXPRESSCOFALLBACK_CHECK_O' THEN c.DCCXPRESSCOFALLBACK_CHECK_O
                WHEN 'DCCMERCHANT_NO_CHECK_O' THEN c.DCCMERCHANT_NO_CHECK_O
                WHEN 'FIRMWARE_VERSION_CHECK' THEN c.FIRMWARE_VERSION_CHECK
                WHEN 'PRINTOUTTYPETEMPLATEDCC_CHECK_C' THEN c.PRINTOUTTYPETEMPLATEDCC_CHECK_C
                WHEN 'CONFIGDOWNLOAD_VERSION_CHECK_C' THEN c.CONFIGDOWNLOAD_VERSION_CHECK_C
                ELSE 1
            END) = 0
) src
ON tgt.ENVIRONMENT = src.ENVIRONMENT
   AND tgt.TERMINAL_IDENTIFIER = src.TERMINAL_IDENTIFIER
   AND tgt.CHECK_COLUMN = src.CHECK_COLUMN
   AND tgt.FIXED_AT_UTC = src.FIXED_AT_UTC
WHEN NOT MATCHED THEN INSERT (ENVIRONMENT, TERMINAL_IDENTIFIER, CHECK_COLUMN, FLAG_NAME, FIX_BIT, VALUE_SENT, TARGET_ID_KIND, TARGET_IDENTIFIER, INSTANCE_IDENTIFIER, LOCATION_NO, CORRELATION_ID, CHANGE_REF, RESOLUTION, FIXED_BY, FIXED_AT_UTC, SRC_LOADED_UTC, CONFIRMED_AT_UTC, COUNTRY_NAME, REGION, INDUSTRY_NAME, BANK_MERCHANT_ID, MERCHANT_NAME, CUSTOMER_NAME, ACQUIRER_NAME, LOCATION_NAME, TERMINAL_BRAND_NAME, TERMINAL_MODEL_NAME, FIRMWARE_VERSION)
VALUES (src.ENVIRONMENT, src.TERMINAL_IDENTIFIER, src.CHECK_COLUMN, src.FLAG_NAME, src.FIX_BIT, src.VALUE_SENT, src.TARGET_ID_KIND, src.TARGET_IDENTIFIER, src.INSTANCE_IDENTIFIER, src.LOCATION_NO, src.CORRELATION_ID, src.CHANGE_REF, src.RESOLUTION, src.FIXED_BY, src.FIXED_AT_UTC, src.SRC_LOADED_UTC, src.CONFIRMED_AT_UTC, src.COUNTRY_NAME, src.REGION, src.INDUSTRY_NAME, src.BANK_MERCHANT_ID, src.MERCHANT_NAME, src.CUSTOMER_NAME, src.ACQUIRER_NAME, src.LOCATION_NAME, src.TERMINAL_BRAND_NAME, src.TERMINAL_MODEL_NAME, src.FIRMWARE_VERSION);
    UPDATE DEV_CORE_AAB.DCC_REMEDIATION.DCC_FIX_REGISTRY r
SET STATUS = 'CONFIRMED',
    CONFIRMED_AT_UTC = (
        SELECT MAX(h.CONFIRMED_AT_UTC) FROM DEV_CORE_AAB.DCC_REMEDIATION.DCC_CONFIRMED_FIXES h
        WHERE h.ENVIRONMENT = r.ENVIRONMENT
          AND h.TERMINAL_IDENTIFIER = r.TERMINAL_IDENTIFIER
          AND h.CHECK_COLUMN = r.CHECK_COLUMN
          AND h.FIXED_AT_UTC = r.FIXED_AT_UTC
    )
WHERE r.ENVIRONMENT = 'PROD' AND r.STATUS = 'FIXED'
  AND EXISTS (
        SELECT 1 FROM DEV_CORE_AAB.DCC_REMEDIATION.DCC_CONFIRMED_FIXES h
        WHERE h.ENVIRONMENT = r.ENVIRONMENT
          AND h.TERMINAL_IDENTIFIER = r.TERMINAL_IDENTIFIER
          AND h.CHECK_COLUMN = r.CHECK_COLUMN
          AND h.FIXED_AT_UTC = r.FIXED_AT_UTC
  );
    COMMIT;
    RETURN 'reconciled';
END;
